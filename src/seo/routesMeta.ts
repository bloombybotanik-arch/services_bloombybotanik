export function normalizeRoutePath(rawPath: string): string {
  if (!rawPath || rawPath === '/') return '/';
  const withoutQuery = rawPath.split('?')[0].split('#')[0];
  const withLeading = withoutQuery.startsWith('/') ? withoutQuery : `/${withoutQuery}`;
  return withLeading.endsWith('/') ? withLeading : `${withLeading}/`;
}

export function getRouteMeta(reqPath: string): RouteMeta | undefined {
  const normalized = normalizeRoutePath(reqPath);
  return ROUTES_META[normalized] || ROUTES_META[reqPath];
}

export function getCanonicalRouteMetaList(): RouteMeta[] {
  const seen = new Set<string>();
  const list: RouteMeta[] = [];
  for (const meta of Object.values(ROUTES_META)) {
    if (meta.noindex) continue;
    const canon = normalizeRoutePath(meta.canonical || meta.path);
    if (canon !== meta.path || seen.has(canon)) continue;
    seen.add(canon);
    list.push(meta);
  }
  return list;
}
